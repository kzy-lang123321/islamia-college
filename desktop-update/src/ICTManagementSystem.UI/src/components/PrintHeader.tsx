import React from 'react';
import { useAppStore } from '../services/store';
import collegeLogo from '../assets/logo.png';

interface PrintHeaderProps {
  title: string;
  subtitle?: string;
  filters?: Record<string, string>;
}

export const PrintHeader: React.FC<PrintHeaderProps> = ({ title, subtitle, filters }) => {
  const { user } = useAppStore();
  const printDate = new Date().toLocaleDateString('en-GB', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit'
  });

  return (
    <div className="print-header-institution print-only border-b border-slate-300 pb-3 mb-4">
      <div className="flex items-start justify-between">
        <div className="flex items-center gap-3">
          <img
            src={collegeLogo}
            alt="ICT Logo"
            className="w-12 h-12 rounded object-contain border border-slate-200 p-0.5"
          />
          <div>
            <h1 className="text-lg font-bold text-slate-900 tracking-tight leading-tight">
              ISLAMIA COLLEGE OF TECHNOLOGY
            </h1>
            <p className="text-[10px] text-slate-600 font-medium">
              Matta Swat, Khyber Pakhtunkhwa • Affiliated with KPK Trade Testing Board (TTB)
            </p>
            <p className="text-[9px] text-slate-500">
              Phone: +92 946 795000 • Web: www.ictswat.edu.pk • Management Information System
            </p>
          </div>
        </div>

        <div className="text-right text-[10px] text-slate-600 leading-tight">
          <div className="font-bold text-xs text-slate-900 uppercase tracking-wide">{title}</div>
          {subtitle && <div className="font-semibold text-slate-700">{subtitle}</div>}
          <div><strong>Printed Date:</strong> {printDate}</div>
          <div><strong>Generated By:</strong> {user?.fullName || 'Cashier / Admin'}</div>
        </div>
      </div>

      {filters && Object.keys(filters).length > 0 && (
        <div className="mt-2 pt-2 border-t border-dashed border-slate-300 flex flex-wrap gap-4 text-[9px] text-slate-700">
          <strong className="text-slate-900">Active Criteria:</strong>
          {Object.entries(filters).map(([k, v]) => (
            v ? <span key={k}><strong>{k}:</strong> {v}</span> : null
          ))}
        </div>
      )}
    </div>
  );
};

